CREATE TABLE IF NOT EXISTS TB_SY_AUTOMATION_RUN (
    JOB_CD VARCHAR(20) NOT NULL,
    RUN_DT DATE NOT NULL,
    STATE_CD VARCHAR(12) NOT NULL,
    LAST_STEP NUMERIC(2) NOT NULL DEFAULT 0,
    START_DTTM TIMESTAMP,
    END_DTTM TIMESTAMP,
    ERROR_CN VARCHAR(300),
    REG_USER_ID VARCHAR(30) NOT NULL,
    REG_DTTM TIMESTAMP NOT NULL,
    MOD_USER_ID VARCHAR(30),
    MOD_DTTM TIMESTAMP,
    CONSTRAINT PK_TB_SY_AUTOMATION_RUN PRIMARY KEY (JOB_CD, RUN_DT),
    CONSTRAINT CK_TB_SY_AUTOMATION_RUN_01 CHECK (JOB_CD IN ('DAILY_OPERATIONS', 'RECEIVABLE_DUNNING')),
    CONSTRAINT CK_TB_SY_AUTOMATION_RUN_02 CHECK (STATE_CD IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT CK_TB_SY_AUTOMATION_RUN_03 CHECK (LAST_STEP BETWEEN 0 AND 7)
);
COMMENT ON TABLE TB_SY_AUTOMATION_RUN IS '일자별 자동 업무 실행의 최신 상태와 완료 단계. 재개 시 최초 시작시각을 보존하며 기간 삭제하지 않는다.';
COMMENT ON COLUMN TB_SY_AUTOMATION_RUN.REG_USER_ID IS '서버 실행 주체; SYSTEM 또는 TB_SY_USER.USER_ID 참조 의도 (FK 미선언)';
COMMENT ON COLUMN TB_SY_AUTOMATION_RUN.MOD_USER_ID IS '서버 변경 주체; SYSTEM 또는 TB_SY_USER.USER_ID 참조 의도 (FK 미선언)';

CREATE TABLE IF NOT EXISTS TB_SY_DELIVERY_TASK (
    TASK_ID UUID NOT NULL,
    EVENT_KEY VARCHAR(160) NOT NULL,
    RCVR_USER_ID VARCHAR(30) NOT NULL,
    RCVR_NM VARCHAR(50) NOT NULL,
    CHANNEL_CD VARCHAR(4) NOT NULL,
    STATE_CD VARCHAR(12) NOT NULL DEFAULT 'PENDING',
    NOTI_TYPE_CD VARCHAR(20) NOT NULL,
    NOTI_CN VARCHAR(300) NOT NULL,
    LINK_SCRN_ID VARCHAR(10),
    LINK_KEY VARCHAR(50),
    MAIL_TO VARCHAR(100),
    MAIL_SUBJECT VARCHAR(200),
    MAIL_BODY TEXT,
    MESSAGE_ID VARCHAR(200),
    NOTI_ID NUMERIC(12),
    BILL_ID VARCHAR(20),
    DUN_STEP NUMERIC(1),
    DUN_SN NUMERIC(5),
    RESEND_YN CHAR(1) NOT NULL DEFAULT 'N',
    SENT_DTTM TIMESTAMP,
    ERROR_CD VARCHAR(60),
    ERROR_CN VARCHAR(300),
    REG_USER_ID VARCHAR(30) NOT NULL,
    REG_DTTM TIMESTAMP NOT NULL,
    MOD_USER_ID VARCHAR(30),
    MOD_DTTM TIMESTAMP,
    CONSTRAINT PK_TB_SY_DELIVERY_TASK PRIMARY KEY (TASK_ID),
    CONSTRAINT UK_TB_SY_DELIVERY_TASK_01 UNIQUE (EVENT_KEY, RCVR_USER_ID, CHANNEL_CD),
    CONSTRAINT FK_TB_SY_DELIVERY_TASK_01 FOREIGN KEY (RCVR_USER_ID) REFERENCES TB_SY_USER (USER_ID),
    CONSTRAINT FK_TB_SY_DELIVERY_TASK_02 FOREIGN KEY (BILL_ID) REFERENCES TB_BL_BILL (BILL_ID),
    CONSTRAINT FK_TB_SY_DELIVERY_TASK_03 FOREIGN KEY (NOTI_ID) REFERENCES TB_SY_NOTI (NOTI_ID) ON DELETE SET NULL,
    CONSTRAINT CK_TB_SY_DELIVERY_TASK_01 CHECK (CHANNEL_CD IN ('SYS', 'MAIL')),
    CONSTRAINT CK_TB_SY_DELIVERY_TASK_02 CHECK (STATE_CD IN ('PENDING', 'SENDING', 'SENT', 'FAILED', 'UNKNOWN', 'SKIPPED')),
    CONSTRAINT CK_TB_SY_DELIVERY_TASK_03 CHECK (NOTI_TYPE_CD IN ('DUN', 'WTHDR', 'CASH_SHORT', 'UPLD_DONE', 'AI_DONE', 'QUOTE_REJ')),
    CONSTRAINT CK_TB_SY_DELIVERY_TASK_04 CHECK (RESEND_YN IN ('Y', 'N')),
    CONSTRAINT CK_TB_SY_DELIVERY_TASK_05 CHECK (
        (CHANNEL_CD = 'SYS' AND MAIL_TO IS NULL AND MAIL_SUBJECT IS NULL AND MAIL_BODY IS NULL AND MESSAGE_ID IS NULL)
        OR (CHANNEL_CD = 'MAIL' AND NOTI_TYPE_CD = 'DUN' AND MAIL_SUBJECT IS NOT NULL AND MAIL_BODY IS NOT NULL
            AND MESSAGE_ID IS NOT NULL AND NOTI_ID IS NULL
            AND (MAIL_TO IS NOT NULL OR (STATE_CD = 'FAILED' AND ERROR_CD IS NOT NULL AND ERROR_CD = 'RECIPIENT_EMAIL_MISSING')))
    ),
    CONSTRAINT CK_TB_SY_DELIVERY_TASK_06 CHECK (
        (NOTI_TYPE_CD = 'DUN' AND BILL_ID IS NOT NULL AND DUN_STEP IS NOT NULL AND DUN_SN IS NOT NULL
            AND DUN_STEP BETWEEN 1 AND 3 AND DUN_SN BETWEEN 1 AND 99999)
        OR (NOTI_TYPE_CD <> 'DUN' AND BILL_ID IS NULL AND DUN_STEP IS NULL AND DUN_SN IS NULL AND RESEND_YN = 'N')
    )
);
COMMENT ON TABLE TB_SY_DELIVERY_TASK IS '이벤트별 수신자와 채널의 영속 전달 증거 및 결과. 알림 정리 후에도 중복방지 키와 당시 사본을 무기한 보존한다.';
COMMENT ON COLUMN TB_SY_DELIVERY_TASK.TASK_ID IS '애플리케이션이 발급하는 서버 UUID; 기본값 없음';
COMMENT ON COLUMN TB_SY_DELIVERY_TASK.MAIL_BODY IS '예약 시 저장한 전체 메일 본문; 생성 후 불변이며 생성 감사는 TASK_ID와 MAIL_BODY 참조를 보존';
COMMENT ON COLUMN TB_SY_DELIVERY_TASK.MESSAGE_ID IS '예약 시 발급하는 메일 식별자; 동일 주소 대표 결과 연결에도 최초 전송 식별자를 유지';
COMMENT ON COLUMN TB_SY_DELIVERY_TASK.LINK_SCRN_ID IS 'TB_SY_MENU.SCRN_ID의 등록 화면 참조 의도 (FK 미선언)';
COMMENT ON COLUMN TB_SY_DELIVERY_TASK.REG_USER_ID IS '서버 실행 주체; SYSTEM 또는 TB_SY_USER.USER_ID 참조 의도 (FK 미선언)';
COMMENT ON COLUMN TB_SY_DELIVERY_TASK.MOD_USER_ID IS '서버 변경 주체; SYSTEM 또는 TB_SY_USER.USER_ID 참조 의도 (FK 미선언)';
